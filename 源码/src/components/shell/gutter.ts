/**
 * 页面的横向页边距
 * ============================================================
 * **整个产品只在这里定义一次。** 顶栏、首页三段、以及以后任何
 * 需要「别贴边」的容器，都用它。
 *
 * ── 为什么单独一个文件，而不是放在 app-nav.tsx 里 ──
 *   app-nav.tsx 是客户端组件（"use client"）。
 *   首页那三段是服务端组件 —— 从客户端模块里 import 一个常量，
 *   会把整个导航组件的依赖拖进服务端渲染的图里。
 *   一个纯字符串常量不该有这种牵连。
 *
 * ── 这个值是怎么定下来的 ──
 *   来回改过几次，每次都记下来，因为「多少合适」这件事没有标准答案，
 *   只有具体屏幕上的具体观感：
 *
 *     1. max-w-[1400px] px-8
 *        1440 下各让 52px；1920 下各让 292px（角上一大片空）
 *     2. 去掉上限，只留 20px
 *        2560 下等于没有边距，内容顶到屏幕边上
 *     3. 固定 56px
 *        比 20 好，但内容仍然铺得太开
 *     4. **112px（现在）**
 *        2560 下两侧各留出 4.4% 的宽度，卡片不再铺满整屏
 *
 *   它是**固定值、不随屏幕变**：按比例算（比如 4vw）的话，
 *   小屏上太窄、大屏上又太宽。而这个值的职责只是「别贴边」——
 *   版心该多宽是另一件事，不该混进同一个数里。
 */
export const NAV_GUTTER = "px-28";