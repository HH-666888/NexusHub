import "server-only";

/**
 * 服务端的「现在」
 * ============================================================
 * 为什么要单独包一层，而不是在组件里直接写 Date.now()：
 *
 *   React 的纯函数规则禁止组件在渲染期间调用 Date.now()、Math.random() 这类
 *   不确定的函数 —— 因为客户端组件会重渲染，结果不稳定就会出问题。
 *
 *   但服务端组件每次请求只渲染一次，「现在」本来就是请求上下文的一部分，
 *   不是渲染的副作用。这里把它显式包成一个函数，是为了让这个区别
 *   在代码上看得见，而不是用一行 eslint-disable 把告警压掉。
 *
 * 换言之：这不是绕过规则，是把「这是请求级的、本就该变化的值」表达出来。
 */
export function serverNow(): number {
  return Date.now();
}