/**
 * 左侧清单：树的另一种视图
 * ============================================================
 * 一句话说清这个文件存在的意义：
 * **画布和左侧清单是同一棵树的两种视图，不是两套数据。**
 *
 * 所以 toOutline 只吃 projectAt 的输出（TaskPoint[]），
 * 不吃日志、不吃 store、不自己维护任何状态。
 * 由此得到一条可以直接说给用户听的性质：
 *   清单里有的，画布上一定找得到；清单里没有的，画布上一张也不多。
 * 如果哪天两者对不上，那一定是某处绕开了这棵树自己造了数据 ——
 * 而不是这个函数算错了。
 *
 * ── 清单为什么只画两级 ──
 *   一级 Agent（总规划）和六道工序是**骨架**：它们数量固定、始终在场，
 *   适合用来做导航。第 3 层起的执行点是**肉**，数量随执行不断增长，
 *   一个「并行构建」下面就可能有几十个 —— 全塞进清单会让清单本身
 *   变成一棵需要滚动的树，失去「一眼看清整件事」的作用。
 *   执行点归画布：那里有位置、有连线、有缩放。
 */

import {
  CONTROL_LAYER_MAX_DEPTH,
  childrenOf,
  rollUpStatus,
  type TaskPoint,
  type TaskPointStatus,
} from "./task-point";

export interface OutlineRow {
  id: string;
  /** 清单只画两级：1 = 一级任务点（标题），2 = 二级任务点（缩进） */
  level: 1 | 2;
  title: string;
  status: TaskPointStatus;
  /** true = 「还没到点」的占位行，界面画成浅色虚线 */
  placeholder: boolean;
  /**
   * 画布上这个任务点对应的节点 id —— 占位行没有对应节点。
   *
   * ── 为什么这个字段必须由内核给，而不是界面自己拿 row.id 去试 ──
   *   真实的行里，row.id **就是**任务点的 id，而画布上节点的 id 也是它
   *   （六道工序用 StageId、七项检查用 `verify:${名字}`，两条路径共用
   *   from-run.ts 里那一份 id 约定）。所以这里给的就是 row.id 本身 ——
   *   但它仍然要显式地是一个字段，理由有两条：
   *
   *   一、**占位行没有对应节点。** 它的 id 是 `${父id}__pending`，
   *       画布上从来没有、也不该有这么一个节点。界面如果拿 row.id 去聚焦，
   *       会得到一个查不到的 id —— 表现是"点了没反应"，看起来像画布的 bug，
   *       而事实是这一行本来就不可点。**把"没有对应节点"写进类型里**
   *       （null 而不是"查不到再说"），界面才有可能诚实地不给它加链接。
   *
   *   二、**它是"清单 ↔ 画布"这条对账关系的唯一落点。**
   *       清单和画布是同一棵树的两种视图，两边的 id 必须对得上；
   *       哪天有人给画布的节点换了 id 规则而没有同步这里，
   *       对不上的地方就是这一个字段 —— 而不是散在界面里的字符串拼接。
   *
   * 取值规则：level 1 / level 2 的实体行 → 自己的 id；占位行 → null。
   */
  canvasNodeId: string | null;
}

/**
 * 占位行的后缀与标题。
 *
 * 抽成常量是因为**测试和界面都要认这两个值**：
 * 界面靠 id 后缀认出「这行不是真任务点，不能点」，
 * 测试靠它断言占位行确实生成了。两处硬编码字符串迟早会写歪一个字符。
 */
const PENDING_SUFFIX = "__pending";
const PENDING_TITLE = "待规划";

/**
 * 把某一刻的任务点列表摊成清单行。
 *
 * 规则：
 *   ① depth === 1 永远输出实体行。
 *      「永远」是要紧的：哪怕一级 Agent 下面还什么都没有，
 *      它自己也是一个真实存在的节点，不能是占位。
 *   ② depth === 2 的、已经生成的，按顺序列在它的一级父节点下面。
 *   ③ 一级任务点**还没有任何二级子节点**时，补一行 placeholder。
 *      这一行是为了回答用户的一个具体疑问：「这里将来会有东西吗？」
 *      答案是「会，只是还没到点」。没有这一行，一片空白既可能表示
 *      「还没开始」也可能表示「已经跑完了没东西」，用户分不出来。
 *   ④ depth >= 3 不进清单。
 *
 * ── 一级行的状态用自己，二级行分两种：有下级才汇总，没下级用自己 ──
 *   一级 Agent 是真的在执行「规划」这件事的节点，它有自己的状态
 *   （planning / running / done），如实显示即可。
 *   二级行里**还有下级**的那些，自己不产出任何东西，状态必须由它下面
 *   已长出来的执行点汇总 —— 见 rollUpStatus。这也顺带解释了到点语义在
 *   清单上的样子：一道工序的执行点还没出生时，汇总结果是 pending（白），
 *   和它「还没到点」的事实是一致的，不需要额外判断。
 *   但二级行里**没有下级**的那些（叶子）必须用它自己的 status：
 *   叶子就是执行单元，它没有下级可汇总。
 *   对叶子调用 rollUpStatus([]) 会一律得到 pending ——
 *   那会让一个已经 done 的叶子在清单上显示成「还没做」，
 *   也就是界面在假装一个不存在的事实。详见下面循环里那段注释。
 *
 * ── 孤儿怎么办 ──
 *   二级点的父节点不在列表里时，它**进不了清单** ——
 *   清单以一级行为骨架，一个接不上骨架的点没有位置可放。
 *   这不是 bug 而是取舍：与其给它编一个假父节点，
 *   不如让它消失，然后由 hasOrphans 在测试里把这件事喊出来。
 *   正常的日志投影不会产出孤儿（父节点总是先出生）。
 */
export function toOutline(points: readonly TaskPoint[]): OutlineRow[] {
  const rows: OutlineRow[] = [];

  for (const root of points) {
    if (root.depth !== 1) continue;

    rows.push({
      id: root.id,
      level: 1,
      title: root.title,
      // 一级节点自己就是执行「规划」的主体，不用汇总
      status: root.status,
      placeholder: false,
      /*
        一级行是实体节点，画布上有它那张卡（六道工序各一张）——
        点这一行跳过去，画布要聚焦的正是这个 id。
      */
      canvasNodeId: root.id,
    });

    const children = childrenOf(points, root.id).filter(
      (p) => p.depth === CONTROL_LAYER_MAX_DEPTH,
    );

    for (const child of children) {
      /*
        二级行的状态：有下级就汇总，没有下级（叶子）就用它自己的 status。

        为什么叶子必须用自身状态 ——
          叶子就是**执行单元**：它自己干活、自己产出，它下面没有任何东西
          可以拿来汇总。而 rollUpStatus([]) 按设计返回 pending
          （空 → 「还没动静」，见 task-point.ts 的规则①，那条本身是对的）。
          错的是**对叶子也去汇总**这个调用方式：一个 status=done 的检查项
          会因为「没有子节点」而被算成 pending，于是清单上写「还没做」，
          画布上、事件日志里却明明白白写着「做完了」。

          这不是配色不好看，是**界面在假装一个不存在的事实** ——
          用户看到的是「这件事没做」，而事实是「已经做完了」。
          这一类谎是这个项目最不能接受的，所以这里按语义分开处理。
          汇总只对**真的还有下级**的二级点有意义：
          它们的进度确实由子树决定，自己没有独立的执行状态可报。
      */
      const grandchildren = childrenOf(points, child.id);
      rows.push({
        id: child.id,
        level: 2,
        title: child.title,
        status:
          grandchildren.length > 0
            ? rollUpStatus(grandchildren) // 还有下级：归纳到子树
            : child.status, // 叶子：如实报它自己的状态
        placeholder: false,
        /*
          二级行也是实体节点。⚠️ 它**不一定**画在画布上：
          画布这一期只给「验收」长了子节点（七项检查，见 forest.ts 的
          checksToChildren），而清单里的二级行来自投影，还包括规格化
          产出的验收条目（`spec:ac-1` 这种）—— 那些点在画布上没有卡片。

          这里**不为此做特判**：清单行说"我在树上对应哪个 id"是事实，
          "画布上有没有画它"是画布那一刻的事实，两者不该在这里互相迁就。
          界面把查不到的情况交给画布去处理（查不到就什么都不做），
          而不是在这里猜"这一行大概点不动"——猜错的方向是**把能点的行
          做成不可点**，那正是这一期最不该出现的事。
        */
        canvasNodeId: child.id,
      });
    }

    if (children.length === 0) {
      rows.push({
        id: `${root.id}${PENDING_SUFFIX}`,
        level: 2,
        title: PENDING_TITLE,
        /*
          placeholder 行的 status 固定 pending。
          它代表的是「未来的东西」，本身没有状态可言；
          给一个确定的值，只是为了让界面不用为它写特例 ——
          pending 的白色和虚线样式在视觉上是同一句话：这儿还没有东西。
        */
        status: "pending",
        placeholder: true,
        /*
          ★ 占位行**没有对应节点** —— 这是这个字段里最要紧的一个取值 ★

          它的 id 是编出来的（`${root.id}__pending`），画布上从来没有、
          将来也不会有一个叫这个名字的节点：它代表的是**还没出生的东西**。
          所以这里给 null，而不是顺手给 root.id：
          给 root.id 的话，"待规划"这一行点下去会跳到它的一级工序上 ——
          看起来功能正常，实际上是在说「待规划的就是那道工序」，
          而事实是「那道工序下面还没有东西」。这两句话不一样，
          而界面上的差别是：一行虚线被做得可点了。
        */
        canvasNodeId: null,
      });
    }
  }

  return rows;
}
