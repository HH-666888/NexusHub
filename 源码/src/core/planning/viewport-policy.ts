/**
 * 视口策略：两种执行模式，只差一个视口
 * ============================================================
 * 用户要的两种跑法：
 *   focus（单次聚焦）—— 一次只跑一件事，视口收进当前那张卡，
 *                        用户盯着它看，像看一台正在加工的车床。
 *   batch（分批执行）—— 一次放一整批下去跑，视口不聚焦任何单卡，
 *                        退到能看见整棵树的位置，看整体进度。
 *
 * ── 这个文件最重要的不是代码，是它划出来的那条线 ──
 *   两种模式下面，**树和清单完全一样**：
 *   同一份日志、同一份 projectAt 的投影、同一份 toOutline 的清单。
 *   跑去哪一步、谁的子节点长出来了、状态是什么，两种模式没有任何区别。
 *   唯一不同的是视口停在哪儿。
 *
 *   所以「将来要实现 batch 模式」这句话，落到代码上就是：
 *   **只改这一个函数**。不需要新的数据结构、不需要在 TaskPoint 上加
 *   mode 字段、不需要两套渲染分支。
 *
 *   把它单独放一个文件，而不是塞进画布组件的某个 useMemo 里，
 *   就是为了让这条线看得见 —— 放在组件里的话，下一个想加 batch 的人
 *   会先去翻渲染逻辑，然后很可能顺手在卡片上加一个 isBatch 判断，
 *   于是「两种模式数据一样」这件事在三个月后就不再成立了。
 *
 * ── 为什么只吃两个 Bounds，不吃树 ──
 *   这个函数不需要知道树长什么样。谁算出的 focusOn（当前卡片的矩形）、
 *   谁算出的 whole（整棵树的包围盒），都不影响它的答案。
 *   参数越窄，能钉死它的测试就越短 —— 一个矩形进、一个矩形出。
 */

export type RunMode = "focus" | "batch";

export interface Bounds {
  x: number;
  y: number;
  w: number;
  h: number;
}

/**
 * 这一刻视口该看哪儿。
 *
 *   focus → focusOn（单次聚焦：视口收进当前那张卡）
 *   batch → whole（分批执行：不聚焦单卡，看全整棵树）
 *
 * 三种模式之外的值在类型上就被挡住了（RunMode 是联合类型），
 * 所以这里不需要 default 分支，也就不存在「加了一种模式但落到默认值上」
 * 这种安静的错误 —— 加模式时编译器会在这里报错。
 *
 * 返回值是**原样返回入参对象**，不做拷贝。
 * 取舍写在明处：它是策略选择，不是数据变换，没有产生新信息；
 * 每次调用都复制一份，只会让「视口变了没有」这件事无法用 === 判断。
 * 代价是调用方必须把返回值当只读快照用，不要就地改它。
 */
export function boundsFor(mode: RunMode, focusOn: Bounds, whole: Bounds): Bounds {
  return mode === "batch" ? whole : focusOn;
}
