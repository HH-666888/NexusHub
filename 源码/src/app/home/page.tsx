import { redirect } from "next/navigation";

/**
 * /home → /
 * ============================================================
 * 首页一度建在 /home 上（为的是不动原来的欢迎页）。
 * 后来把新首页挪到了根路径，这个地址就空出来了。
 *
 * 留一个重定向而不是直接删掉，原因很实际：
 *   · 已经发出去的链接、浏览器书签、以及端到端脚本里的断言，
 *     都可能还指着 /home
 *   · 直接删会得到一个 404 —— 而 404 会让人以为「这个功能没了」，
 *     重定向则让人感觉不到发生过迁移
 *
 * 用 redirect 而不是 rewrite：这里要的是**地址栏跟着变**。
 * 停在 /home 上看根路径的内容，会让「我到底在哪个页面」变得含糊，
 * 以后再贴链接也会继续贴 /home。
 */
export default function HomeRedirect() {
  redirect("/");
}